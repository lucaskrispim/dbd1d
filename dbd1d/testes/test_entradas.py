def test_duplicata_nova_em_ar_n2_o2_nao_e_tolerada(tmp_path):
    origem = proveniencia.pasta_do_caso("ar_n2_o2")
    _precisa(origem / "bolsigdb.dat")
    for nome in ("bolsigdb.dat", "bolsigdb.log"):
        (tmp_path / nome).write_text((origem / nome).read_text())
    blocos = proveniencia.blocos_carregados(tmp_path)
    ref = next(b for b in blocos if b.tipo == "EXCITATION" and b.limiar is not None and b.alvo == "N2")
    texto = (tmp_path / "bolsigdb.dat").read_text().splitlines()
    i = next(k for k, l in enumerate(texto) if l.strip() == ref.nome)
    fim = next(k for k in range(i + 1, len(texto)) if texto[k].startswith("-----"))
    fim = next(k for k in range(fim + 1, len(texto)) if texto[k].startswith("-----"))
    copia = [texto[i - 1], "N2 -> N2*(copia)"] + texto[i + 1:fim + 1]
    (tmp_path / "bolsigdb.dat").write_text("\n".join(texto + [""] + copia) + "\n")
    with open(tmp_path / "bolsigdb.log", "a") as f:
        f.write("N2->N2*(copia)\n")
    novas = _duplicatas_novas(tmp_path, "ar_n2_o2")
    assert any("N2 -> N2*(copia)" in p for p in novas), novas


