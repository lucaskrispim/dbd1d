LIMITE_CABECALHO = 20000


@pytest.mark.parametrize("caso", proveniencia.CASOS)
def test_colunas_das_tabelas_casam_com_a_quimica(caso):
    pasta = proveniencia.pasta_do_caso(caso)
    _precisa(pasta / "tabela_energia.dat")
    _precisa(pasta / "quimica.json")
    cabecalho = (pasta / "tabela_energia.dat").read_text().splitlines()[1].lstrip("#")
    colunas = [x.strip()[2:-1] for x in cabecalho.split(", ") if x.strip().startswith("k(")]
    por_coluna = _processos_da_quimica(pasta)
    assert sorted(por_coluna) == list(range(len(por_coluna)))
    assert all(len(s) == 1 for s in por_coluna.values())
    esperado = [next(iter(por_coluna[c])) for c in range(len(por_coluna))]
    linhas = (pasta / "tabela_energia.dat").read_text().splitlines()
    if len(linhas[1]) >= LIMITE_CABECALHO:
        # the header written by the ZDPlasKin tables is cut at about 20000 characters (cases with more
        # than 979 processes): check the columns that fit and the width of the data rows
        assert colunas[:-1] == esperado[:len(colunas) - 1]
        assert len(linhas[2].split()) == 10 + len(esperado)
    else:
        assert colunas == esperado


def razoes_fora_da_faixa(blocos, minimo=0.1, maximo=10.0):
    """(name, ratio) of every loaded <-> block whose statistical weight ratio is not physical."""
    # an exact 0 is the explicit "no superelastic inverse" switch of the Phelps based cases
    # (n2, n2_exemplo, ar_n2); it is reported as a concern, not tested here
    return [(b.nome, b.razao_pesos) for b in blocos
            if b.razao_pesos and not minimo <= b.razao_pesos <= maximo]


