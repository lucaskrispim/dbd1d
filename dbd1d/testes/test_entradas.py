def _linhas_do_log(pasta):
    return [l.strip() for l in (pasta / "bolsigdb.log").read_text().splitlines()
            if l.strip() and not l.startswith("#")]


def _precisa(*caminhos):
    # inside a test body a skipif mark does nothing: skip now when a file is not distributed
    faltam = [str(c) for c in caminhos if not pathlib.Path(c).exists()]
    if faltam:
        pytest.skip(f"needs {', '.join(faltam)}, which is not distributed (casos/README.md)")


