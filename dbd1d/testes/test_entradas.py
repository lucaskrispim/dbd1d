def _processos_da_quimica(pasta):
    """BOLSIG+ processes the chemistry cites, in column order."""
    q = json.loads((pasta / "quimica.json").read_text())
    por_coluna = {}
    for r, c in zip(q["reacoes"], q["coluna_bolsig"]):
        if c is not None:
            por_coluna.setdefault(c, set()).add(r.split(":", 1)[1] if r.startswith("bolsig:") else r)
    return por_coluna


