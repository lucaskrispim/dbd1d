ENTRADAS_CASO = ("kinet.inp", "quimica.json", "bolsigdb.dat", "transporte.json", "gas.json", "tabela_energia_tg.dat")


def _repo_temporario(tmp_path):
    import subprocess

    def git(*args):
        subprocess.run(["git", *args], cwd=tmp_path, check=True, capture_output=True)

    git("init", "-q")
    git("config", "user.email", "t@example.org")
    git("config", "user.name", "t")
    (tmp_path / "codigo.py").write_text("x = 1\n")
    (tmp_path / "outro.py").write_text("y = 1\n")
    caso = tmp_path / "casos" / "a"
    caso.mkdir(parents=True)
    for nome in ENTRADAS_CASO:
        (caso / nome).write_text(nome)
    git("add", "-A")
    git("commit", "-q", "-m", "base")
    return caso


def test_registro_arvore_limpa(tmp_path):
    caso = _repo_temporario(tmp_path)
    r = proveniencia.registro(tmp_path, ["codigo.py"], caso)
    assert r["sujo"] == []
    assert len(r["commit"]) == 40
    assert set(r["sha256_entradas"]) == set(ENTRADAS_CASO)
    assert set(r["sha256"]) == {"codigo.py"}


