    blocos = proveniencia.blocos_carregados(tmp_path)
    ref = next(b for b in blocos if b.tipo == "EXCITATION" and b.limiar is not None and b.alvo == "N2")
    texto = (tmp_path / "bolsigdb.dat").read_text().splitlines()
