! Synthetic module for the tests of dbd1d, written by the authors. It only
! imitates the blocks of a module generated by the ZDPlasKin preprocessor that
! the reader of quimica_zdp.py parses (species, charges, reaction signs, the
! rate subroutine, the reaction orders and the source matrix), with the
! constructs the reader must evaluate as Fortran does: IF / ELSE IF / ELSE
! blocks, a one-line IF, integer division, single precision literals, a
! PARAMETER constant and the total neutral density.
module sintetico
  data species_charge(1:species_max) &
  /-1, 0, 0, 1/
  data species_name(1:species_max) &
  /"E   ","A   ","B   ","A^+ "/
  data reaction_sign(1:reactions_max) &
  /"bolsig:A->A^+","E+A^+=>A      ","A+B=>B+B      ","B=>A          ","A+A^+=>A^++A  "/
contains
subroutine ZDPlasKin_reac_rates(Time)
  implicit none
  double precision, intent(in) :: Time
  double precision :: Tgas
  double precision :: EN
  double precision :: Te
  double precision :: ANY_NEUTRAL
  DOUBLE PRECISION, PARAMETER :: K0 = 2.5D-11, TREF = 300.0D0
  DOUBLE PRECISION :: FATOR, TEFF
  call ZDPlasKin_bolsig_rates()
  Tgas = ZDPlasKin_cfg(1)
  EN  = ZDPlasKin_cfg(3)
  Te  = ZDPlasKin_cfg(4)
  call ZDPlasKin_get_density_total(ALL_NEUTRAL=ANY_NEUTRAL)
  TEFF = TGAS + 0.39 * EN**2 * (3/2)
  IF (TGAS .GT. 600.0D0 .AND. EN < 100.0D0) THEN
    FATOR = 2.0D0
  ELSE IF (TGAS > 450.0D0) THEN
    FATOR = 3.0D0
  ELSE
    FATOR = 1.0D0
  END IF
  rrt(01) = bolsig_rates(bolsig_pointer(1))
  rrt(02) = 1.5D-7 * (TREF/TE)**0.7 * (7/2)
  rrt(03) = K0 * FATOR * EXP(-1.0/3.0 * TEFF / TREF)
  rrt(04) = 1.0D3 * ANY_NEUTRAL / 2.5D19
  rrt(05) = 4.0D-10
  IF (EN .GE. 300.0D0) rrt(05) = 8.0D-10
end subroutine ZDPlasKin_reac_rates
subroutine ZDPlasKin_fex(neq,t,y,ydot)
  call ZDPlasKin_reac_rates(t)
  rrt(01) = rrt(01) * density(01) * density(02)
  rrt(02) = rrt(02) * density(01) * density(04)
  rrt(03) = rrt(03) * density(02) * density(03)
  rrt(04) = rrt(04) * density(03)
  rrt(05) = rrt(05) * density(02) * density(04)
end subroutine ZDPlasKin_fex
subroutine ZDPlasKin_reac_source_matrix(reac_rate_local,reac_source_local)
  reac_source_local(:,:) = 0.0d0
  reac_source_local(01,01) = + reac_rate_local(01)
  reac_source_local(02,01) = - reac_rate_local(01)
  reac_source_local(04,01) = + reac_rate_local(01)
  reac_source_local(01,02) = - reac_rate_local(02)
  reac_source_local(04,02) = - reac_rate_local(02)
  reac_source_local(02,02) = + reac_rate_local(02)
  reac_source_local(02,03) = - reac_rate_local(03)
  reac_source_local(03,03) = + reac_rate_local(03)
  reac_source_local(03,04) = - reac_rate_local(04)
  reac_source_local(02,04) = + reac_rate_local(04)
end subroutine ZDPlasKin_reac_source_matrix
end module sintetico
